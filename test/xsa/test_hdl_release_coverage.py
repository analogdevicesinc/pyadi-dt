class GateStageMismatch(Exception):
    """A known gap failed at a different stage than the one it documents."""


def _design_id(design: dict[str, Any]) -> str:
    return f"{design['project']}/{design['carrier']}"


def _supported(design: dict[str, Any]) -> bool:
    return design["status"] != "unsupported"


# ---------------------------------------------------------------------------
# Offline: inventory consistency
# ---------------------------------------------------------------------------


def test_inventory_is_well_formed():
    ids = [_design_id(d) for d in DESIGNS]
    assert len(ids) == len(set(ids)), "duplicate project/carrier entries"
    assert len(DESIGNS) > 100, "inventory looks truncated"
    for design in DESIGNS:
        assert design["class"] in CLASSES, _design_id(design)
        assert design["status"] in STATUSES, _design_id(design)
        assert design["arch"] in {"arm", "arm64", "microblaze"}, _design_id(design)
        for dts in design["kuiper_projects"].values():
            assert dts in design["kernel_dts"], _design_id(design)


@pytest.mark.parametrize(
    "design", [d for d in DESIGNS if _supported(d)], ids=_design_id
)
def test_supported_design_names_real_profile_and_builder(design):
    profiles = set(ProfileManager().list_profiles())
    builders = {type(b).__name__ for b in NodeBuilder._DEFAULT_BUILDERS}

    assert design["profile"] in profiles
    assert set(design["extra_profiles"]) <= profiles
    if design["status"] == "full":
        assert design["builder"] in builders
    else:
        assert design["builder"] is None


def test_unsupported_designs_claim_nothing():
    for design in DESIGNS:
        if not _supported(design):
            assert design["profile"] is None, _design_id(design)
            assert design["builder"] is None, _design_id(design)


def test_designs_without_inputs_say_why():
    for design in DESIGNS:
        if not design["kernel_dts"] or not design["kuiper_projects"]:
            assert design["reason"], _design_id(design)
        else:
            assert design["reason"] is None, _design_id(design)


def test_known_gaps_refer_to_supported_inventory_entries():
    supported_dirs = {k for d in DESIGNS if _supported(d) for k in d["kuiper_projects"]}
    for directory, (stage, reason) in KNOWN_GAPS.items():
        assert directory in supported_dirs, directory
        assert stage in STAGES, directory
        assert reason, directory


def test_kuiper_board_manifest_tracks_the_same_release():
    manifest = json.loads((CONFIG_DIR / "kuiper_boards.json").read_text())
    assert manifest["release"] == INVENTORY["release"]
    boards = manifest["boards"]
    profiles = set(ProfileManager().list_profiles())
    for design in DESIGNS:
        for directory in design["kuiper_projects"]:
            assert directory.split("/")[0] in boards, directory
    for name, board in boards.items():
        assert board["status"] in STATUSES, name
        if board["profile"] is not None:
            assert board["profile"] in profiles, name


# ---------------------------------------------------------------------------
# Online: run the pipeline on every released XSA
# ---------------------------------------------------------------------------

ONLINE = os.getenv("ADI_XSA_KUIPER_ONLINE") == "1"
LINUX_REPO = os.getenv("ADI_LINUX_REPO")
_REPORT: list[dict[str, Any]] = []


def _stage_can_run(stage: str) -> bool:
    return stage != "roles" or bool(LINUX_REPO)


def _gate_cases() -> list[Any]:
    cases = []
    for design in DESIGNS:
        if not design["kuiper_projects"]:
            cases.append(
                pytest.param(
                    design,
                    None,
                    id=_design_id(design),
                    marks=pytest.mark.skip(reason=design["reason"]),
                )
            )
            continue
        for directory in design["kuiper_projects"]:
            marks = []
            if not _supported(design):
                marks.append(
                    pytest.mark.xfail(
                        strict=True,
                        raises=AssertionError,
                        reason="design is unsupported in the inventory",
                    )
                )
            elif directory in KNOWN_GAPS and _stage_can_run(KNOWN_GAPS[directory][0]):
                stage, reason = KNOWN_GAPS[directory]
                marks.append(
                    pytest.mark.xfail(
                        strict=True,
                        raises=AssertionError,
                        reason=f"{stage}: {reason}",
                    )
                )
            cases.append(
                pytest.param(
                    design,
                    directory,
                    id=f"{_design_id(design)}:{directory}",
                    marks=marks,
                )
            )
    return cases


@pytest.fixture(scope="session")
def release_xsas() -> dict[str, Path]:
    """Extract every XSA of the inventory's Kuiper release (cached on disk)."""
    release = INVENTORY["release"]
    cache_dir = Path(
        os.getenv("ADI_KUIPER_CACHE_DIR", Path.home() / ".cache" / "adidt" / "kuiper")
    )
    tarball = download_boot_partition_release(release=release, cache_dir=cache_dir)
    directories = sorted({k for d in DESIGNS for k in d["kuiper_projects"]})
    return extract_release_xsas(tarball, directories, cache_dir / f"{release}_xsa")


@pytest.fixture(scope="session")
def kernel_tree(tmp_path_factory) -> Path | None:
    """Device-tree sources of the inventory's kernel commit, or ``None``."""
    if not LINUX_REPO:
        return None
    out = tmp_path_factory.mktemp("kernel_dts")
    archive = subprocess.run(
        [
            "git",
            "-C",
            LINUX_REPO,
            "archive",
            INVENTORY["linux_commit"],
            "arch/arm/boot/dts/xilinx",
            "arch/arm64/boot/dts/xilinx",
            "arch/microblaze/boot/dts",
            "include/dt-bindings",
        ],
        capture_output=True,
        check=False,
    )
    if archive.returncode != 0:
        pytest.fail(
            f"ADI_LINUX_REPO lacks commit {INVENTORY['linux_commit']}: "
            f"{archive.stderr.decode(errors='replace').strip()}"
        )
    subprocess.run(["tar", "-x", "-C", str(out)], input=archive.stdout, check=True)
    return out


