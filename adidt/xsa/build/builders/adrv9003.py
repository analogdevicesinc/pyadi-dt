"""XSA builder for the ADRV9003 (Navassa) transceiver."""

from __future__ import annotations

from typing import Any

from ....devices.transceivers import ADRV9003
from ...parse.topology import XsaTopology


class ADRV9003Builder:
    """Render the ADRV9003 SPI/JESD top device.

    The XSA contains the AXI RX/TX cores; this builder supplies the Navassa
    PHY node and leaves those cores to the generic JESD renderer.  The
    device-specific profile is intentionally supplied through
    ``adrv9003_board.trx_profile_props`` because ADRV9003 profiles are
    generated by TES and are not interchangeable with Talise profiles.
    """

    _KEYWORDS = ("adrv9001", "adrv9002", "adrv9003")

    @classmethod
    def _is_navassa(cls, value: str) -> bool:
        lower = value.lower()
        return any(key in lower for key in cls._KEYWORDS)

    def matches(self, topology: XsaTopology, cfg: dict[str, Any]) -> bool:
        return any(
            self._is_navassa(c.name) or c.ip_type in {
                "axi_adrv9001",
                "axi_adrv9002",
                "axi_adrv9003",
            }
            for c in topology.converters
        ) or any(
            self._is_navassa(j.name)
            for j in (*topology.jesd204_rx, *topology.jesd204_tx)
        )

    def build_nodes(
        self,
        node_builder: Any,
        topology: XsaTopology,
        cfg: dict[str, Any],
        ps_clk_label: str,
        ps_clk_index: int | None,
        gpio_label: str,
    ) -> list[str]:
        board_cfg = cfg.get("adrv9003_board", {})
        if not isinstance(board_cfg, dict):
            board_cfg = {}
        converter = next(
            (c for c in topology.converters if self._is_navassa(c.name)),
            None,
        )
        if converter is None:
            converter = next(
                (c for c in topology.converters if c.ip_type.startswith("axi_adrv900")),
                None,
            )
        if converter is None:
            return []

        rx = next((j for j in topology.jesd204_rx if self._is_navassa(j.name)), None)
        tx = next((j for j in topology.jesd204_tx if self._is_navassa(j.name)), None)
        if rx is None or tx is None:
            return []

        spi_cs = int(board_cfg.get("spi_cs", converter.spi_cs or 0))
        spi_hz = int(board_cfg.get("spi_max_frequency", 25_000_000))
        phy = ADRV9003(
            label=str(board_cfg.get("label", "adc0_adrv9002")),
            compatible_strings=["adi,adrv9003", "adrv9003"],
            spi_max_hz=spi_hz,
            reset_gpio=board_cfg.get("reset_gpio"),
        )
        profile_props = board_cfg.get("trx_profile_props", [])
        if not isinstance(profile_props, list) or not all(
            isinstance(item, str) for item in profile_props
        ):
            raise ValueError("adrv9003_board.trx_profile_props must be a list of strings")

        ps_ref = (
            f"<&{ps_clk_label} {ps_clk_index}>"
            if ps_clk_index is not None
            else f"<&{ps_clk_label}>"
        )
        rendered = phy.render_dt(
            cs=spi_cs,
            context={
                "clock_names_value": '"jesd_rx_clk", "jesd_tx_clk", "dev_clk"',
                "clocks_value": f"<&{rx.name.replace('-', '_')}>, <&{tx.name.replace('-', '_')}>, {ps_ref}",
                "link_ids": f"{int(board_cfg.get('rx_link_id', 0))} {int(board_cfg.get('tx_link_id', 1))}",
                "jesd204_inputs": f"<&{rx.name.replace('-', '_')} 0 0>, <&{tx.name.replace('-', '_')} 0 1>",
                "profile_props": profile_props,
                "gpio_label": gpio_label,
            },
        )
        return [rendered]

    def skips_generic_jesd(self) -> bool:
        return False

    def skip_ip_types(self) -> set[str]:
        return {"axi_adrv9001", "axi_adrv9002", "axi_adrv9003"}
